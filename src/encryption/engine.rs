    // ---- KMS-wrapped data keys (#26), with a local mock KMS ----

    use crate::encryption::envelope::test_support::MockKms;

    fn same_kms(kms: &MockKms) -> Arc<dyn KmsKeyWrapper> {
        Arc::new(MockKms::new(kms.kms_key_id(), [0x5a; 32]))
    }

    fn active_key(engine: &EncryptionEngine, key_id: &str) -> Vec<u8> {
        engine.keys.lock().unwrap()[key_id].clone()
    }

    fn previous_keys(engine: &EncryptionEngine, key_id: &str) -> Vec<Vec<u8>> {
        engine
            .previous_keys
            .lock()
            .unwrap()
            .get(key_id)
            .cloned()
            .unwrap_or_default()
    }

    /// Engines in different processes (or after a restart) load the same stored data key,
    /// and keep earlier versions after a rotation.
    async fn engine_kms_roundtrip<DB: KeyManagerBackend>(pool: Pool<DB>) {
        let kms = MockKms::unique();
        let config = || EncryptionConfig::new(EncryptionAlgorithm::AES256GCM);

        let first = EncryptionEngine::with_kms(config(), &pool, same_kms(&kms))
            .await
            .unwrap();
        let v1 = active_key(&first, "default");
        assert_eq!(v1.len(), 32);

        // Restart: the same key is recovered from the stored KMS-wrapped blob
        let second = EncryptionEngine::with_kms(config(), &pool, same_kms(&kms))
            .await
            .unwrap();
        assert_eq!(active_key(&second, "default"), v1);
        assert!(previous_keys(&second, "default").is_empty());

        assert_eq!(second.rotate_kms_key(&pool).await.unwrap(), 2);
        let v2 = active_key(&second, "default");
        assert_ne!(v1, v2);
        assert_eq!(previous_keys(&second, "default"), vec![v1.clone()]);

        let third = EncryptionEngine::with_kms(config(), &pool, same_kms(&kms))
            .await
            .unwrap();
        assert_eq!(active_key(&third, "default"), v2);
        assert_eq!(previous_keys(&third, "default"), vec![v1.clone()]);

        // Another key id is a separate key
        let other =
            EncryptionEngine::with_kms(config().with_key_id("other"), &pool, same_kms(&kms))
                .await
                .unwrap();
        assert_ne!(active_key(&other, "other"), v1);
        assert_ne!(active_key(&other, "other"), v2);

        let stored = DB::load_kms_wrapped_keys(&pool, "engine/default", "aws", kms.kms_key_id())
            .await
            .unwrap();
        assert_eq!(stored.len(), 2);

        // rotate_kms_key needs a KMS source
        let static_engine = EncryptionEngine::new_with_pool(
            config().with_key_source(KeySource::Static(
                "dGVzdGtleTE5ODc2NTQzMjEwOTg3NjU0MzIxMHRlc3Q=".to_string(),
            )),
            &pool,
        )
        .await
        .unwrap();
        assert!(matches!(
            static_engine.rotate_kms_key(&pool).await,
            Err(EncryptionError::InvalidConfiguration(_))
        ));
    }

    /// Engines starting at the same time converge on one stored data key.
    async fn engine_kms_concurrent_first_load<DB: KeyManagerBackend>(pool: Pool<DB>) {
        let kms = MockKms::unique();
        let tasks: Vec<_> = (0..6)
            .map(|_| {
                let pool = pool.clone();
                let kms = same_kms(&kms);
                tokio::spawn(async move {
                    let config = EncryptionConfig::new(EncryptionAlgorithm::AES256GCM);
                    let engine = EncryptionEngine::with_kms(config, &pool, kms)
                        .await
                        .unwrap();
                    active_key(&engine, "default")
                })
            })
            .collect();
        let mut keys = Vec::new();
        for task in tasks {
            keys.push(task.await.unwrap());
        }
        assert!(keys.windows(2).all(|w| w[0] == w[1]));
        let stored = DB::load_kms_wrapped_keys(&pool, "engine/default", "aws", kms.kms_key_id())
            .await
            .unwrap();
        assert_eq!(stored.len(), 1);
    }

    /// Payloads encrypted before a restart and before a rotation can be decrypted.
    async fn engine_kms_payload_roundtrip<DB: KeyManagerBackend>(pool: Pool<DB>) {
        let kms = MockKms::unique();
        let config = || EncryptionConfig::new(EncryptionAlgorithm::AES256GCM);
        let payload = json!({"ssn": "123-45-6789", "amount": 10});

        let first = EncryptionEngine::with_kms(config(), &pool, same_kms(&kms))
            .await
            .unwrap();
        let before_rotation = first.encrypt_payload(&payload, &["ssn"]).await.unwrap();

        let second = EncryptionEngine::with_kms(config(), &pool, same_kms(&kms))
            .await
            .unwrap();
        assert_eq!(
            second.decrypt_payload(&before_rotation).await.unwrap(),
            payload
        );
        second.rotate_kms_key(&pool).await.unwrap();
        let after_rotation = second.encrypt_payload(&payload, &["ssn"]).await.unwrap();
        assert_eq!(
            second.decrypt_payload(&before_rotation).await.unwrap(),
            payload
        );

        let third = EncryptionEngine::with_kms(config(), &pool, same_kms(&kms))
            .await
            .unwrap();
        assert_eq!(
            third.decrypt_payload(&before_rotation).await.unwrap(),
            payload
        );
        assert_eq!(
            third.decrypt_payload(&after_rotation).await.unwrap(),
            payload
        );
        // The engine that did not rotate cannot read the new version until it reloads
        assert!(first.decrypt_payload(&after_rotation).await.is_err());
    }

