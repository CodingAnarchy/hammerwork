    fn static_engine(key_id: &str, key: &str) -> EncryptionConfig {
        EncryptionConfig::new(EncryptionAlgorithm::AES256GCM)
            .with_key_id(key_id)
            .with_key_source(KeySource::Static(key.to_string()))
    }

    const KEY_A: &str = "dGVzdGtleTE5ODc2NTQzMjEwOTg3NjU0MzIxMHRlc3Q=";
    const KEY_B: &str = "QUFBQUFBQUFBQUFBQUFBQUFBQUFBQUFBQUFBQUFBQUE=";

    #[tokio::test]
    async fn test_decryption_key_for_previous_key_id() {
        let old = EncryptionEngine::new(static_engine("old", KEY_A))
            .await
            .unwrap();
        let payload = json!({"ssn": "123-45-6789"});
        let encrypted = old.encrypt_payload(&payload, &["ssn"]).await.unwrap();
        assert_eq!(encrypted.metadata.key_id, "old");

        let new = EncryptionEngine::new(static_engine("new", KEY_B))
            .await
            .unwrap();
        assert!(matches!(
            new.decrypt_payload(&encrypted).await,
            Err(EncryptionError::KeyManagement(_))
        ));

        let new = new
            .with_decryption_key("old", &KeySource::Static(KEY_A.to_string()))
            .await
            .unwrap();
        assert_eq!(new.decrypt_payload(&encrypted).await.unwrap(), payload);
        // New payloads still use the engine's own key
        let fresh = new.encrypt_payload(&payload, &["ssn"]).await.unwrap();
        assert_eq!(fresh.metadata.key_id, "new");
        assert!(old.decrypt_payload(&fresh).await.is_err());

        // The engine's own key id cannot be replaced
        assert!(matches!(
            new.with_decryption_key("new", &KeySource::Static(KEY_A.to_string()))
                .await,
            Err(EncryptionError::InvalidConfiguration(_))
        ));
    }

    #[tokio::test]
    async fn test_payload_hash_is_keyed() {
        let engine = EncryptionEngine::new(static_engine("k", KEY_A))
            .await
            .unwrap();
        let payload = json!({"ssn": "123-45-6789"});
        let encrypted = engine.encrypt_payload(&payload, &["ssn"]).await.unwrap();

        // Not the plain SHA-256 of the plaintext, which could be brute-forced
        let plain = engine.calculate_payload_hash(&serde_json::to_vec(&payload).unwrap());
        assert!(encrypted.metadata.payload_hash.starts_with("hmac-sha256:"));
        assert!(!encrypted.metadata.payload_hash.contains(&plain));

        // A different key gives a different hash
        let other = EncryptionEngine::new(static_engine("k", KEY_B))
            .await
            .unwrap();
        let other_encrypted = other.encrypt_payload(&payload, &["ssn"]).await.unwrap();
        assert_ne!(
            encrypted.metadata.payload_hash,
            other_encrypted.metadata.payload_hash
        );

        // Tampering with the hash is detected
        let mut tampered = encrypted.clone();
        tampered.metadata.payload_hash = format!("hmac-sha256:{}", "0".repeat(64));
        assert!(matches!(
            engine.decrypt_payload(&tampered).await,
            Err(EncryptionError::DecryptionFailed(_))
        ));
    }

